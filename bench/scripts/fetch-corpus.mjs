#!/usr/bin/env node
// Fetches and generates every benchmark corpus into bench/corpus/.
//
//   node scripts/fetch-corpus.mjs                    # fetch + verify against manifest.json
//   node scripts/fetch-corpus.mjs --update-manifest  # (maintainers) rewrite hashes
//   node scripts/fetch-corpus.mjs --skip-huge        # skip the largest synthetic size
//
// Third-party files are not committed. Instead corpus/manifest.json pins the
// source (npm version or git tag + path) and the SHA-256 of every file, and
// this script refuses to continue if a download does not match. Generated
// corpora use fixed seeds; their hashes are recorded too so drift (for
// example from a different Tailwind version) is visible.
import { copyFileSync, existsSync, readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { BENCH_DIR, CORPUS_DIR, sha256, sha256File, writeFile, listFiles } from '../lib/util.mjs';
import { BOOTSTRAP_TAG, BOOTSTRAP_EXAMPLES, BULMA_TAG, BULMA_DOCS } from '../lib/corpora.mjs';
import { generateTailwind } from './gen-tailwind.mjs';
import { generateSynthetic, SYNTHETIC_SIZES } from './gen-synthetic.mjs';

const args = new Set(process.argv.slice(2));
const UPDATE = args.has('--update-manifest');
const SKIP_HUGE = args.has('--skip-huge');
const MANIFEST = join(CORPUS_DIR, 'manifest.json');
const require = createRequire(import.meta.url);

const manifest = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')) : {};
const next = { note: 'Generated by scripts/fetch-corpus.mjs --update-manifest. Do not edit by hand.', corpora: {} };
let failures = 0;

function check(corpus, key, actual) {
  next.corpora[corpus] ??= { files: {} };
  next.corpora[corpus].files[key] = actual;
  const expected = manifest.corpora?.[corpus]?.files?.[key];
  if (UPDATE) return;
  if (!expected) {
    console.warn(`  ! ${corpus}/${key}: not in manifest (run with --update-manifest)`);
    failures++;
  } else if (expected !== actual) {
    console.error(`  x ${corpus}/${key}: sha256 ${actual} != manifest ${expected}`);
    failures++;
  }
}

function download(url, dest) {
  if (existsSync(dest)) return;
  mkdirSync(dirname(dest), { recursive: true });
  const r = spawnSync('curl', ['--fail', '-sSL', '--retry', '3', '-o', dest, url], { stdio: 'inherit' });
  if (r.status !== 0) throw new Error(`download failed: ${url}`);
}

function npmFile(pkg, path) {
  return join(dirname(require.resolve(`${pkg}/package.json`)), path);
}

function npmVersion(pkg) {
  return JSON.parse(readFileSync(npmFile(pkg, 'package.json'), 'utf8')).version;
}

// --- Bootstrap -------------------------------------------------------------
{
  console.log(`bootstrap: css from npm bootstrap@${npmVersion('bootstrap')}, examples from twbs/bootstrap@${BOOTSTRAP_TAG}`);
  const dir = join(CORPUS_DIR, 'bootstrap');
  mkdirSync(dir, { recursive: true });
  copyFileSync(npmFile('bootstrap', 'dist/css/bootstrap.css'), join(dir, 'bootstrap.css'));
  check('bootstrap', 'bootstrap.css', sha256File(join(dir, 'bootstrap.css')));
  for (const name of BOOTSTRAP_EXAMPLES) {
    const dest = join(dir, 'examples', name, 'index.astro');
    download(`https://raw.githubusercontent.com/twbs/bootstrap/${BOOTSTRAP_TAG}/site/src/assets/examples/${name}/index.astro`, dest);
    check('bootstrap', `examples/${name}/index.astro`, sha256File(dest));
  }
  next.corpora.bootstrap.source = { css: `npm:bootstrap@${npmVersion('bootstrap')}/dist/css/bootstrap.css`, content: `github:twbs/bootstrap@${BOOTSTRAP_TAG}/site/src/assets/examples/*/index.astro` };
}

// --- Bulma -----------------------------------------------------------------
{
  console.log(`bulma: css from npm bulma@${npmVersion('bulma')}, docs from jgthms/bulma@${BULMA_TAG}`);
  const dir = join(CORPUS_DIR, 'bulma');
  mkdirSync(dir, { recursive: true });
  copyFileSync(npmFile('bulma', 'css/bulma.css'), join(dir, 'bulma.css'));
  check('bulma', 'bulma.css', sha256File(join(dir, 'bulma.css')));
  for (const page of BULMA_DOCS) {
    const dest = join(dir, 'docs', `${page}.html`);
    download(`https://raw.githubusercontent.com/jgthms/bulma/${BULMA_TAG}/docs/documentation/${page}.html`, dest);
    check('bulma', `docs/${page}.html`, sha256File(dest));
  }
  next.corpora.bulma.source = { css: `npm:bulma@${npmVersion('bulma')}/css/bulma.css`, content: `github:jgthms/bulma@${BULMA_TAG}/docs/documentation/**/*.html` };
}

// --- Tailwind --------------------------------------------------------------
{
  const version = npmVersion('@tailwindcss/cli');
  console.log(`tailwind: generating pages, building CSS with @tailwindcss/cli@${version}`);
  const dir = join(CORPUS_DIR, 'tailwind');
  rmSync(join(dir, 'pages'), { recursive: true, force: true });
  generateTailwind(dir);
  const cli = join(BENCH_DIR, 'node_modules', '.bin', 'tailwindcss');
  const r = spawnSync(cli, ['-i', join(dir, 'input.css'), '-o', join(dir, 'tailwind.css')], { cwd: dir, stdio: ['ignore', 'inherit', 'pipe'], encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`tailwind build failed:\n${r.stderr}`);
  check('tailwind', 'tailwind.css', sha256File(join(dir, 'tailwind.css')));
  const pagesHash = sha256(listFiles(join(dir, 'pages'), /\.html$/).map((p) => sha256File(p)).join('\n'));
  check('tailwind', 'pages/*.html (combined)', pagesHash);
  next.corpora.tailwind.source = { css: `generated: @tailwindcss/cli@${version} -i input.css (see scripts/gen-tailwind.mjs)`, content: 'generated: scripts/gen-tailwind.mjs, seed 0x7a11, 40 pages' };
}

// --- Synthetic -------------------------------------------------------------
for (const [size, spec] of Object.entries(SYNTHETIC_SIZES)) {
  if (SKIP_HUGE && size === 'huge') continue;
  console.log(`synthetic-${size}: ${spec.rules} rules x ${spec.files} files`);
  const dir = join(CORPUS_DIR, 'synthetic', size);
  rmSync(dir, { recursive: true, force: true });
  generateSynthetic(dir, spec);
  const key = `synthetic-${size}`;
  check(key, 'styles.css', sha256File(join(dir, 'styles.css')));
  check(key, 'content/*.html (combined)', sha256(listFiles(join(dir, 'content'), /\.html$/).map((p) => sha256File(p)).join('\n')));
  next.corpora[key].source = { generated: `scripts/gen-synthetic.mjs (${size})` };
}

// --- Edge (committed) ------------------------------------------------------
for (const p of listFiles(join(CORPUS_DIR, 'edge'), /./)) {
  check('edge', p.slice(join(CORPUS_DIR, 'edge').length + 1), sha256File(p));
}
next.corpora.edge.source = { committed: 'corpus/edge' };

if (UPDATE) {
  writeFileSync(MANIFEST, `${JSON.stringify(next, null, 2)}\n`);
  console.log(`wrote ${MANIFEST}`);
} else if (failures) {
  console.error(`${failures} file(s) did not match corpus/manifest.json.`);
  process.exit(1);
} else {
  console.log('all corpus files match corpus/manifest.json');
}
