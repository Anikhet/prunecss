// Renders a results JSON file as Markdown tables.
//   node lib/report.mjs results/<file>.json   # regenerate the .md next to it
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ms = (s) => (s < 0.1 ? `${(s * 1000).toFixed(2)} ms` : s < 10 ? `${(s * 1000).toFixed(0)} ms` : `${s.toFixed(2)} s`);
const pm = (x) => `${ms(x.mean)} ± ${ms(x.stddev)}`;
const kb = (b) => (b >= 1e6 ? `${(b / 1e6).toFixed(2)} MB` : `${(b / 1e3).toFixed(1)} kB`);
const mib = (k) => `${(k / 1024).toFixed(1)} MiB`;
const pct = (a, b) => `${((100 * a) / b).toFixed(1)}%`;
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => `\`${esc(s).replace(/`/g, "'")}\``;

/** Ratio a/b with propagated standard deviation. */
function ratio(a, b) {
  const r = a.mean / b.mean;
  const sd = r * Math.sqrt((a.stddev / a.mean) ** 2 + (b.stddev / b.mean) ** 2);
  return { r, sd };
}
const fmtRatio = ({ r, sd }) => `${r.toFixed(1)}× ± ${sd.toFixed(1)}`;

function median(xs) {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : NaN;
}

export function renderMarkdown(res, categories) {
  const e = res.environment;
  const L = [];
  const timed = res.corpora.filter((c) => c.tools.prunecss.cli);
  L.push(`# prunecss vs PurgeCSS — ${e.date.slice(0, 10)} on \`${e.host}\``);
  L.push('');
  L.push(`> **${res.label}.** Generated by \`bench/run.mjs\`${res.settings.quick ? ' in --quick mode (few runs: do not quote these numbers)' : ''}. Raw data: the \`.json\` file with the same name. Every number below can be recomputed from it.`);
  L.push('');

  // Headline
  const cli = timed.map((c) => ratio(c.tools.purgecss.cli, c.tools.prunecss.cli).r);
  const api = timed.filter((c) => c.tools.purgecss.inProcessApi).map((c) => ratio(c.tools.purgecss.inProcessApi, c.tools.prunecss.cli).r);
  if (cli.length) {
    L.push('## Headline');
    L.push('');
    L.push(`- **CLI wall time:** prunecss was ${Math.min(...cli).toFixed(1)}–${Math.max(...cli).toFixed(1)}× faster than the PurgeCSS CLI across ${cli.length} corpora (median ${median(cli).toFixed(1)}×), mean of ${res.settings.hyperfine.runs} runs each.`);
    if (api.length) L.push(`- **Against PurgeCSS's best case** (its JS API in a warmed-up process, no Node startup or file reads) prunecss's *whole CLI run* was ${Math.min(...api).toFixed(1)}–${Math.max(...api).toFixed(1)}× faster (median ${median(api).toFixed(1)}×).`);
    const rss = timed.map((c) => c.tools.purgecss.peakRss.medianKB / c.tools.prunecss.peakRss.medianKB);
    L.push(`- **Peak memory:** PurgeCSS used ${Math.min(...rss).toFixed(1)}–${Math.max(...rss).toFixed(1)}× the RSS of prunecss (median of ${res.settings.rssRuns} runs per tool).`);
    const real = (x) => (x?.matchingStaticDom ?? 0) - (x?.rewrittenNotRemoved ?? 0);
    const fr = res.corpora.map((c) => [c.name, real(c.correctness.falseRemovals.prunecss)]).filter(([, n]) => n);
    const rw = res.corpora.map((c) => [c.name, c.correctness.falseRemovals.prunecss?.rewrittenNotRemoved ?? 0]).filter(([, n]) => n);
    L.push(`- **Correctness:** ${fr.length ? `prunecss removed selectors that match the static DOM in ${fr.map(([n, k]) => `${n} (${k})`).join(', ')} — see "Selectors removed that the content uses".` : 'prunecss removed no selector that matches the static DOM of any corpus.'}${rw.length ? ` prunecss also *rewrote* selectors in ${rw.map(([n, k]) => `${n} (${k})`).join(', ')}.` : ''}`);
    L.push('');
  }

  // Environment
  L.push('## Machine and versions');
  L.push('');
  L.push('| | |');
  L.push('|---|---|');
  const h = e.hardware;
  const rows = [
    ['CPU', `${h.cpuModel}, ${h.logicalCpus} logical CPUs${h.hypervisor ? ` (VM: ${h.hypervisor})` : ''}`],
    ['Memory', `${h.memoryGiB} GiB`],
    ['OS', `${e.os.distro ?? ''} (${e.os.platform}, kernel ${e.os.kernel})`],
    ['CPU governor / no_turbo', `${h.governor} / ${h.noTurbo}`],
    ['Load average at start', h.loadAvg.join(', ')],
    ...Object.entries(e.versions).map(([k, v]) => [k, v ?? 'n/a']),
    ['hyperfine settings', `-N, --warmup ${res.settings.hyperfine.warmup}, --runs ${res.settings.hyperfine.runs}`],
    ['tinybench settings', JSON.stringify(res.settings.tinybench)],
  ];
  for (const [k, v] of rows) L.push(`| ${k} | ${esc(v)} |`);
  L.push('');

  // Corpora
  L.push('## Corpora');
  L.push('');
  L.push('| corpus | description | input CSS | content files | content bytes |');
  L.push('|---|---|---:|---:|---:|');
  for (const c of res.corpora) L.push(`| ${c.name} | ${esc(c.description)} | ${kb(c.input.cssBytes)} | ${c.input.contentFiles} | ${kb(c.input.contentBytes)} |`);
  L.push('');

  // Speed
  if (timed.length) {
    L.push('## Speed: end-to-end CLI wall time (hyperfine)');
    L.push('');
    L.push('Mean ± standard deviation; "× slower" is tool mean / prunecss mean with propagated σ.');
    L.push('');
    L.push('| corpus | tool | mean ± σ | median | min … max | user + sys | × slower than prunecss |');
    L.push('|---|---|---:|---:|---:|---:|---:|');
    for (const c of timed) {
      for (const [id, t] of Object.entries(c.tools)) {
        if (!t.cli) continue;
        L.push(`| ${c.name} | ${t.label} | ${pm(t.cli)} | ${ms(t.cli.median)} | ${ms(t.cli.min)} … ${ms(t.cli.max)} | ${ms(t.cli.user + t.cli.system)} | ${id === 'prunecss' ? '1.0×' : fmtRatio(ratio(t.cli, c.tools.prunecss.cli))} |`);
      }
    }
    L.push('');
    L.push('Node.js startup on its own (part of every PurgeCSS CLI row above):');
    L.push('');
    L.push('| command | mean ± σ |');
    L.push('|---|---:|');
    for (const n of res.nodeStartup) L.push(`| ${code(n.command)} | ${pm(n)} |`);
    L.push('');

    const apiRows = timed.flatMap((c) => Object.entries(c.tools).filter(([, t]) => t.inProcessApi).map(([, t]) => [c, t]));
    if (apiRows.length) {
      L.push('## Speed: PurgeCSS JS API in-process (tinybench) — PurgeCSS\'s best case');
      L.push('');
      L.push('Inputs preloaded into memory, JIT warmed up. Compared with the **full** prunecss CLI run (process start, file reads and writes included), so the comparison favours PurgeCSS.');
      L.push('');
      L.push('| corpus | tool | API mean ± σ | samples | prunecss CLI mean | API ÷ prunecss CLI |');
      L.push('|---|---|---:|---:|---:|---:|');
      for (const [c, t] of apiRows) L.push(`| ${c.name} | ${t.label} | ${pm(t.inProcessApi)} | ${t.inProcessApi.samples} | ${ms(c.tools.prunecss.cli.mean)} | ${fmtRatio(ratio(t.inProcessApi, c.tools.prunecss.cli))} |`);
      L.push('');
    }

    L.push(`## Peak memory (max RSS, ${e.versions.peakRssTool})`);
    L.push('');
    L.push('| corpus | tool | median | min … max |');
    L.push('|---|---|---:|---:|');
    for (const c of timed) for (const t of Object.values(c.tools)) if (t.peakRss) L.push(`| ${c.name} | ${t.label} | ${mib(t.peakRss.medianKB)} | ${mib(t.peakRss.minKB)} … ${mib(t.peakRss.maxKB)} |`);
    L.push('');
  }

  // Size
  L.push('## Output size (every file minified by the same lightningcss first)');
  L.push('');
  L.push('"tool raw" is the file as the tool wrote it; the other columns are after the shared minifier.');
  L.push('');
  L.push('| corpus | file | tool raw | minified | gzip -9 | brotli -q 11 | minified vs input |');
  L.push('|---|---|---:|---:|---:|---:|---:|');
  for (const c of res.corpora) {
    const inp = c.input.size;
    L.push(`| ${c.name} | input | ${kb(inp.raw)} | ${kb(inp.minified)} | ${kb(inp.gzip)} | ${kb(inp.brotli)} | 100% |`);
    for (const t of Object.values(c.tools)) L.push(`| ${c.name} | ${t.label} | ${kb(t.size.raw)} | ${kb(t.size.minified)} | ${kb(t.size.gzip)} | ${kb(t.size.brotli)} | ${pct(t.size.minified, inp.minified)} |`);
  }
  L.push('');

  // Correctness
  L.push('## Correctness: which selectors each tool kept');
  L.push('');
  L.push('Selectors are compared as `at-rule context | selector` keys after the shared minifier. "Matches static DOM" means the selector, with pseudo-classes stripped, matches an element when the content files are parsed as HTML (css-select). That is a lower bound on what a page needs: classes added by JavaScript are invisible to it.');
  L.push('');
  L.push('| corpus | input selectors | ' + 'kept by prunecss | kept by purgecss | kept by purgecss (tailwind-extractor) | kept by both (vs default purgecss) | only prunecss | only purgecss |');
  L.push('|---|---:|---:|---:|---:|---:|---:|---:|');
  for (const c of res.corpora) {
    const k = c.correctness.kept;
    const cmp = c.correctness.comparisons['prunecss-vs-purgecss'];
    L.push(`| ${c.name} | ${c.correctness.inputSelectors} | ${k.prunecss} | ${k.purgecss} | ${k['purgecss-tailwind-extractor'] ?? '–'} | ${cmp.keptByBoth} | ${cmp.keptOnlyByPrunecss.count} | ${cmp.keptOnlyByOther.count} |`);
  }
  L.push('');
  L.push('Categories used below:');
  L.push('');
  for (const [k, v] of Object.entries(categories)) L.push(`- **${k}**: ${v}`);
  L.push('');

  for (const c of res.corpora) {
    for (const [name, cmp] of Object.entries(c.correctness.comparisons)) {
      L.push(`### ${c.name}: ${name.replace('prunecss-vs-', 'prunecss vs ')}`);
      L.push('');
      for (const [side, title] of [['keptOnlyByPrunecss', 'Kept only by prunecss'], ['keptOnlyByOther', `Kept only by ${cmp.other}`]]) {
        const s = cmp[side];
        L.push(`**${title}: ${s.count}**`);
        L.push('');
        if (!s.count) continue;
        L.push('| category | count | of which match static DOM | examples (context) — names the other tool did not find |');
        L.push('|---|---:|---:|---|');
        for (const [cat, v] of Object.entries(s.byCategory)) {
          const ex = v.examples.map((x) => {
            const miss = side === 'keptOnlyByPrunecss' ? x.notExtractedByPurgecss : x.notScannedByPrunecss;
            return `${code(x.selector)}${x.context ? ` (${esc(x.context)})` : ''}${miss?.length ? ` — missing ${miss.map(esc).join(' ')}` : ''}`;
          }).join('<br>');
          L.push(`| ${cat} | ${v.count} | ${v.matchStaticDom} | ${ex} |`);
        }
        L.push('');
      }
    }
  }

  L.push('## Selectors removed that the content uses (possible false removals)');
  L.push('');
  L.push('A selector here was in the input, is missing from the tool\'s output, and matches the static DOM of the content (state pseudo-classes such as `:hover` count as "can match"). "exact" excludes matches found only after dropping a `:not()`/`:has()` whose argument was a state pseudo-class. "rewritten" rows are not missing CSS: the tool printed the selector in another form (shown after →), which may itself change behaviour.');
  L.push('');
  L.push('| corpus | tool | removed | match static DOM | exact | rewritten | by category | examples |');
  L.push('|---|---|---:|---:|---:|---:|---|---|');
  for (const c of res.corpora) {
    for (const [id, fr] of Object.entries(c.correctness.falseRemovals)) {
      const ex = fr.examples.slice(0, 5).map((x) => `${code(x.selector)}${x.rewrittenTo ? ` → ${code(x.rewrittenTo)}` : ''}${x.context ? ` (${esc(x.context)})` : ''}`).join('<br>');
      L.push(`| ${c.name} | ${c.tools[id].label} | ${fr.removed} | ${fr.matchingStaticDom} | ${fr.exact} | ${fr.rewrittenNotRemoved ?? 0} | ${esc(Object.entries(fr.byCategory).map(([k, v]) => `${k}: ${v}`).join(', ')) || '–'} | ${ex || '–'} |`);
    }
  }
  L.push('');
  L.push('## Kept selectors that match nothing in the static DOM (upper bound on leftover CSS)');
  L.push('');
  L.push('Includes CSS for states JavaScript adds (`.show`, `.collapsing`), so this over-counts real bloat.');
  L.push('');
  L.push('| corpus | tool | kept but unmatched | by category |');
  L.push('|---|---|---:|---|');
  for (const c of res.corpora) for (const [id, b] of Object.entries(c.correctness.staticallyUnmatchedKept)) L.push(`| ${c.name} | ${c.tools[id].label} | ${b.count} | ${esc(Object.entries(b.byCategory).map(([k, v]) => `${k}: ${v}`).join(', '))} |`);
  L.push('');

  // Where prunecss loses
  L.push('## Where prunecss loses');
  L.push('');
  const losses = [];
  for (const c of res.corpora) {
    for (const [id, t] of Object.entries(c.tools)) {
      if (id === 'prunecss') continue;
      const p = c.tools.prunecss;
      if (t.cli && t.cli.mean < p.cli.mean) losses.push(`- **${c.name}**: ${t.label} CLI was faster (${pm(t.cli)} vs ${pm(p.cli)}).`);
      if (t.size.minified < p.size.minified) losses.push(`- **${c.name}**: ${t.label} output is smaller: ${kb(t.size.minified)} vs ${kb(p.size.minified)} minified (${kb(t.size.brotli)} vs ${kb(p.size.brotli)} brotli). prunecss kept ${c.correctness.comparisons[`prunecss-vs-${id}`].keptOnlyByPrunecss.count} selectors that ${t.label} removed.`);
      if (t.peakRss && t.peakRss.medianKB < p.peakRss.medianKB) losses.push(`- **${c.name}**: ${t.label} used less memory.`);
    }
    const fr = c.correctness.falseRemovals.prunecss;
    const gone = fr ? fr.examples.filter((x) => !x.rewrittenTo) : [];
    const moved = fr ? fr.examples.filter((x) => x.rewrittenTo) : [];
    if (fr && fr.matchingStaticDom - (fr.rewrittenNotRemoved ?? 0) > 0) losses.push(`- **${c.name}**: prunecss removed ${fr.matchingStaticDom - (fr.rewrittenNotRemoved ?? 0)} selector(s) that match the content's static DOM, e.g. ${gone.slice(0, 4).map((x) => code(x.selector)).join(', ')}.`);
    if (moved.length) losses.push(`- **${c.name}**: prunecss rewrote ${fr.rewrittenNotRemoved} selector(s) into a different selector, e.g. ${moved.slice(0, 2).map((x) => `${code(x.selector)} → ${code(x.rewrittenTo)}`).join(', ')} (compared after the shared minifier).`);
    const cmp = c.correctness.comparisons['prunecss-vs-purgecss'];
    const purgeOnly = cmp.keptOnlyByOther.count;
    if (purgeOnly) losses.push(`- **${c.name}**: PurgeCSS kept ${purgeOnly} selector(s) that prunecss removed (${esc(Object.entries(cmp.keptOnlyByOther.byCategory).map(([k, v]) => `${k}: ${v.count}`).join(', '))}). Check the examples: PurgeCSS splits names such as \`bg-green-400/50\` into parts, so it can keep the rule for a part the page does not use.`);
  }
  L.push(...(losses.length ? losses : ['- Nothing measured here.']));
  L.push('');
  L.push('Not measured, and known gaps: both tools run with no safelist and with explicit file lists. prunecss always keeps tag, attribute and pseudo-only selectors (PurgeCSS removes tags whose names never appear in the text), which is most of the size difference. The static-DOM check cannot see classes added by JavaScript at runtime, so it undercounts what a page needs; a browser coverage run would be the next step.');
  L.push('');
  return `${L.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  const { CATEGORIES } = await import('./selectors.mjs');
  writeFileSync(file.replace(/\.json$/, '.md'), renderMarkdown(JSON.parse(readFileSync(file, 'utf8')), CATEGORIES));
}
